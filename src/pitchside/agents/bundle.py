class Bundle(BaseModel):
    model_config = ConfigDict(arbitrary_types_allowed=True)

    path: Path
    manifest: BundleManifest
    narratives: list[NarrativeEntry]
    audit: list[AuditEntry]
    usage: list[UsageRecord]
    findings: list[Finding]
    stats: list[Snapshot]
    answer_key: Optional[dict[str, Any]] = None


def load_bundle(path: Path) -> Bundle:
    """Read and validate a bundle directory (every file against its model)."""
    path = Path(path)

    def jsonl(name: str) -> list[str]:
        return [line for line in (path / FILES[name]).read_text(encoding="utf-8").splitlines() if line.strip()]

    key_file = path / FILES["answer_key"]
    return Bundle(
        path=path,
        manifest=BundleManifest.model_validate_json((path / FILES["manifest"]).read_text(encoding="utf-8")),
        narratives=TypeAdapter(list[NarrativeEntry]).validate_json(
            (path / FILES["narratives"]).read_text(encoding="utf-8")),
        audit=[AuditEntry.model_validate_json(line) for line in jsonl("audit")],
        usage=[UsageRecord.model_validate_json(line) for line in jsonl("usage")],
        findings=FINDINGS_ADAPTER.validate_json((path / FILES["findings"]).read_text(encoding="utf-8")),
        stats=[Snapshot.model_validate_json(line) for line in jsonl("stats")],
        answer_key=json.loads(key_file.read_text(encoding="utf-8")) if key_file.exists() else None,
    )


def bundle_json_schema() -> dict[str, Any]:
    """One JSON document describing every file of a bundle (``pitchside schema --bundle``)."""
    def schema(model: Any) -> dict[str, Any]:
        return TypeAdapter(model).json_schema()

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Pitchside run bundle",
        "description": __doc__.strip().splitlines()[0],
        "bundle_version": BUNDLE_VERSION,
        "files": {
            FILES["manifest"]: schema(BundleManifest),
            FILES["narratives"]: schema(list[NarrativeEntry]),
            FILES["audit"]: {"description": "One JSON object per line.", **schema(AuditEntry)},
            FILES["usage"]: {"description": "One JSON object per line.", **schema(UsageRecord)},
            FILES["stats"]: {"description": "One JSON object per line.", **schema(Snapshot)},
            FILES["findings"]: {"$ref": "finding.schema.json"},
            FILES["events"]: {"description": "One event per line.", "$ref": "event.schema.json"},
            FILES["answer_key"]: {"description": "Generator answer key (synthetic ground truth).", "type": "object"},
            FILES["evaluation"]: {"description": "Scores against the answer key, see pitchside eval-agents.",
                                  "type": "object"},
            FILES["overlay"]: {"description": "Timed overlays derived from the bundle, see docs/OVERLAY.md.",
                               "$ref": "overlay.schema.json"},
        },
    }
