"""Run bundles: everything one match run produced, as plain JSON files the static demo (milestone 5) replays.

    <match_id>__<run_id>/
      manifest.json      what ran: label, pipeline and model config, prompt versions, personas, languages,
                         injected faults, budget, counts
      events.jsonl       the synthetic event stream
      stats.jsonl        stats-engine snapshots every 30 s of match clock
      findings.json      every finding with its evidence
      narratives.json    per job: overlay timing, the narrative shown (claims, persona x language texts, source),
                         its ledger (every number and where it came from), drafts and checks
      audit.jsonl        every step of every job: prompts (version + digest), claims, verdicts, retries, fallbacks
      usage.jsonl        every model call: tokens, cost, latency, linked to job, step and attempt
      answer_key.json    what the generator planted (synthetic ground truth)
      evaluation.json    scores against the answer key (written by the evaluation)
      overlay.json       the timed overlay contract the web UI replays, derived from the files above
                         (``pitchside.render.overlay``, docs/OVERLAY.md)

The manifest's ``label`` is what the UI must show: recorded runs are never presented as live, offline runs are
labelled as fake-model output, and any injected fault is announced.
"""

from __future__ import annotations

import json
import subprocess
from importlib import metadata
from pathlib import Path
from typing import Any, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter

from ..llm.config import Role
from ..llm.prices import PRICE_TABLE_VERSION
from ..llm.usage import UsageRecord, total_cost
from ..schema import to_json_line
from ..stats.engine import Snapshot
from ..stats.findings import FINDINGS_ADAPTER, Finding
from .contracts import (
    AuditEntry, ClaimCheck, Draft, JobKind, JobRecord, Ledger, Narrative, TeamRef, fav_persona,
)
from .pipeline import MatchRun
from .prompting import ROLES, prompt_version

BUNDLE_VERSION = "1.1"  # 1.1: overlay.json added
LIVE_LABEL = "Recorded run generated by the live pipeline"
OFFLINE_LABEL = "Offline run (fake model client): narratives are deterministic stand-ins, not model output"
FAULTS_SUFFIX = " (faults were deliberately injected to show recovery)"
DISPLAY_S = {"goal": 25.0, "big_chance": 15.0, "counter_attack": 10.0, "spell_start": 20.0, "spell_end": 12.0,
             "recap": 45.0}
FILES = {"manifest": "manifest.json", "events": "events.jsonl", "stats": "stats.jsonl",
         "findings": "findings.json", "narratives": "narratives.json", "audit": "audit.jsonl",
         "usage": "usage.jsonl", "answer_key": "answer_key.json", "evaluation": "evaluation.json",
         "overlay": "overlay.json"}


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class FeaturedPlayer(_Frozen):
    player_id: str
    name: str
    team_id: str
    persona: str


class PipelineInfo(_Frozen):
    pitchside_version: str
    git_commit: Optional[str]
    llm_mode: Literal["fake", "foundry"]
    api: str
    deployments: dict[str, str]
    price_model: str
    price_table_version: str
    reasoning_effort: str
    max_output_tokens: dict[str, int]
    prompt_versions: dict[str, str]
    max_explainer_attempts: int
    interpreter_tools: Literal["local", "mcp"] = Field(description="How the interpreter reached the stats tools.")
    mcp_server: Optional[str] = Field(default=None, description="'in-process' or the server URL, when tools are mcp.")


class FaultInfo(_Frozen):
    injected: bool
    plan: Optional[str] = None
    rules: list[str] = Field(default_factory=list)
    fired: list[dict[str, Any]] = Field(default_factory=list, description="Every fault that actually fired.")


class BudgetInfo(_Frozen):
    match_budget_usd: float
    spent_usd: float
    model_calls: int
    budget_fallbacks: int = Field(description="Jobs that got a template because of the budget. Should be 0.")
    exhausted: Optional[str] = None


class Counts(_Frozen):
    events: int
    findings: int
    jobs: int
    model_jobs: int
    template_jobs: int
    model_fallbacks: int = Field(description="Jobs sent to the agents that ended with a template narrative.")
    recaps: int


class BundleManifest(_Frozen):
    kind: Literal["pitchside-run-bundle"] = "pitchside-run-bundle"
    bundle_version: str = BUNDLE_VERSION
    label: str = Field(description="Show this in the UI, verbatim.")
    run_id: str
    match_id: str
    created_utc: str
    wall_s: float
    generator: dict[str, Any]
    home: TeamRef
    away: TeamRef
    final_score: dict[str, int]
    languages: list[str]
    personas: list[str]
    featured_players: list[FeaturedPlayer]
    pipeline: PipelineInfo
    faults: FaultInfo
    budget: BudgetInfo
    counts: Counts
    files: dict[str, str] = Field(default_factory=lambda: dict(FILES))


class Display(_Frozen):
    """When an overlay for this job is on screen, in match-clock seconds."""

    show_at_s: float
    hide_at_s: float
    priority: float = Field(description="0-1; higher wins when overlays overlap.")


class NarrativeEntry(_Frozen):
    job_id: str
    kind: JobKind
    label: str
    finding_id: Optional[str]
    team_id: Optional[str]
    clock_s: float
    route: Literal["model", "template"]
    display: Display
    narrative: Narrative
    ledger: Ledger
    drafts: list[Draft]
    checks: list[ClaimCheck]


def label_for(mode: str, faults: bool) -> str:
    return (LIVE_LABEL if mode == "foundry" else OFFLINE_LABEL) + (FAULTS_SUFFIX if faults else "")


def display_for(record: JobRecord, finding: Optional[Finding]) -> Display:
    if record.kind == "recap":
        key, priority = "recap", 1.0
    elif finding is not None and finding.status == "start":
        key, priority = "spell_start", finding.severity
    elif finding is not None and finding.status == "end":
        key, priority = "spell_end", min(finding.severity, 0.4)
    else:
        key = record.label
        priority = 1.0 if record.label == "goal" else (finding.severity if finding else 0.5)
    return Display(show_at_s=record.clock_s, hide_at_s=round(record.clock_s + DISPLAY_S.get(key, 15.0), 1),
                   priority=round(priority, 3))


def _git_commit() -> Optional[str]:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=5,
                             cwd=Path(__file__).resolve().parent)
        return out.stdout.strip() or None if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def _version() -> str:
    try:
        return metadata.version("pitchside")
    except metadata.PackageNotFoundError:
        return "unknown"


def run_usage(run: MatchRun) -> list[UsageRecord]:
    """This run's usage rows in job order; within a job, in the order they were logged (chronological)."""
    if run.usage_log is None:
        return []
    order = {r.job_id: n for n, r in enumerate(run.records)}
    rows = [u for u in run.usage_log.read() if u.run_id == run.run_id]
    return sorted(rows, key=lambda u: order.get(u.finding_id or "", 10**6))


def build_manifest(run: MatchRun, usage: list[UsageRecord]) -> BundleManifest:
    settings = run.settings
    key = run.answer_key or {}
    model_jobs = [r for r in run.records if r.route == "model"]
    budget_fallbacks = sum("budget" in (r.narrative.reason or "") for r in run.records)
    final = run.events[-1].final_score if hasattr(run.events[-1], "final_score") else None
    personas = ["analyst", "casual", *(fav_persona(p) for p in run.featured)]
    featured = [FeaturedPlayer(player_id=p, name=run.facts.player(p).name, team_id=run.facts.player(p).team_id,
                               persona=fav_persona(p)) for p in run.featured]
    deployments = {r.value: (getattr(settings, f"model_{r.value}") or "fake") for r in Role}
    return BundleManifest(
        label=label_for(settings.mode, bool(run.fault_plan)),
        run_id=run.run_id, match_id=run.match_id, created_utc=run.started_utc, wall_s=run.wall_s,
        generator={k: key.get(k) for k in ("seed", "storyline", "description")},
        home=run.facts.home, away=run.facts.away,
        final_score={"home": final.home, "away": final.away} if final else {},
        languages=[l.code for l in run.config.languages], personas=personas, featured_players=featured,
        pipeline=PipelineInfo(
            pitchside_version=_version(), git_commit=_git_commit(), llm_mode=settings.mode,
            api=settings.foundry_api if settings.mode == "foundry" else "fake", deployments=deployments,
            price_model=settings.price_model, price_table_version=PRICE_TABLE_VERSION,
            reasoning_effort=settings.reasoning_effort,
            max_output_tokens={r.value: settings.max_output(r) for r in Role},
            prompt_versions={role: prompt_version(role) for role in ROLES},
            max_explainer_attempts=run.config.max_attempts, interpreter_tools=settings.tools,
            mcp_server=run.tools_location,
        ),
        faults=FaultInfo(injected=bool(run.fault_plan), plan=run.fault_plan.name if run.fault_plan else None,
                         rules=run.fault_plan.describe() if run.fault_plan else [],
                         fired=sorted(run.faults_fired, key=lambda f: (f["job_id"], f["role"], f["attempt"] or 0))),
        budget=BudgetInfo(match_budget_usd=settings.match_budget_usd,
                          spent_usd=total_cost(usage),
                          model_calls=sum(u.status != "refused" for u in usage), budget_fallbacks=budget_fallbacks,
                          exhausted=run.budget_exhausted),
        counts=Counts(events=len(run.events), findings=len(run.findings), jobs=len(run.records),
                      model_jobs=len(model_jobs), template_jobs=len(run.records) - len(model_jobs),
                      model_fallbacks=sum(r.narrative.source == "template" for r in model_jobs),
                      recaps=sum(r.kind == "recap" for r in run.records)),
    )


def narrative_entries(run: MatchRun) -> list[NarrativeEntry]:
    findings = {f.finding_id: f for f in run.findings}
    return [NarrativeEntry(job_id=r.job_id, kind=r.kind, label=r.label, finding_id=r.finding_id, team_id=r.team_id,
                           clock_s=r.clock_s, route=r.route, display=display_for(r, findings.get(r.finding_id or "")),
                           narrative=r.narrative, ledger=r.ledger, drafts=r.drafts, checks=r.checks)
            for r in run.records]


def bundle_dir_name(match_id: str, run_id: str) -> str:
    return f"{match_id}__{run_id}"


def write_bundle(run: MatchRun, out_dir: Path, evaluation: Optional[dict[str, Any]] = None) -> Path:
    path = Path(out_dir) / bundle_dir_name(run.match_id, run.run_id)
    path.mkdir(parents=True, exist_ok=True)
    usage = run_usage(run)

    def lines(name: str, rows) -> None:
        with (path / FILES[name]).open("w", encoding="utf-8", newline="\n") as handle:
            for row in rows:
                handle.write(row + "\n")

    def dump(name: str, data: Any) -> None:
        (path / FILES[name]).write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                                        newline="\n")

    lines("usage", [u.model_dump_json() for u in usage])
    dump("manifest", build_manifest(run, usage).model_dump(mode="json"))
    lines("events", [to_json_line(e) for e in run.events])
    lines("stats", [s.model_dump_json() for s in run.snapshots])
    dump("findings", FINDINGS_ADAPTER.dump_python(run.findings, mode="json"))
    dump("narratives", [e.model_dump(mode="json") for e in narrative_entries(run)])
    lines("audit", [a.model_dump_json() for r in run.records for a in r.audit])
    if run.answer_key is not None:
        dump("answer_key", run.answer_key)
    if evaluation is not None:
        dump("evaluation", evaluation)
    from ..render.overlay import write_overlay  # derived from the files just written, the same way as later

    write_overlay(path)
    return path


