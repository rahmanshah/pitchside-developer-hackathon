"""Static checks on web/: colour contrast of the design tokens, self-contained assets, honest badge strings."""

from __future__ import annotations

import json
import re
import unittest
from pathlib import Path

from pitchside.render import crests

WEB = Path(__file__).resolve().parents[1] / "web"
TOKENS = (WEB / "css" / "tokens.css").read_text(encoding="utf-8")

# (foreground, background, minimum ratio): every text colour on every surface it is used on.
TEXT_PAIRS = [
    *[("chalk", bg, 4.5) for bg in ("ink-0", "ink-1", "ink-2", "ink-3", "pitch", "pitch-surround")],
    *[("chalk-2", bg, 4.5) for bg in ("ink-0", "ink-1", "ink-2", "ink-3")],
    *[("chalk-3", bg, 4.5) for bg in ("ink-0", "ink-1", "ink-2")],
    *[(fg, bg, 4.5) for fg in ("amber", "ok", "fault", "bad") for bg in ("ink-0", "ink-1", "ink-2")],
    ("amber-ink", "amber", 4.5),
    ("ink-0", "chalk", 4.5),
    ("amber", "pitch", 4.5),
]


def token(name: str) -> str:
    match = re.search(rf"--{re.escape(name)}:\s*(#[0-9a-fA-F]{{6}})\s*;", TOKENS)
    assert match, f"--{name} is not a #rrggbb token in tokens.css"
    return match.group(1).lower()


class TokenTests(unittest.TestCase):
    def test_text_colours_meet_wcag_aa_on_their_surfaces(self) -> None:
        for fg, bg, minimum in TEXT_PAIRS:
            ratio = crests.contrast(token(fg), token(bg))
            self.assertGreaterEqual(ratio, minimum, f"--{fg} on --{bg}: {ratio:.2f}")

    def test_the_pitch_colour_matches_the_crest_contrast_checks(self) -> None:
        self.assertEqual(token("pitch"), crests.PITCH_BG)


class AssetTests(unittest.TestCase):
    def files(self, pattern: str):
        return [p for p in WEB.rglob(pattern) if "data" not in p.relative_to(WEB).parts]

    def test_no_external_scripts_styles_or_fonts(self) -> None:
        for path in self.files("*.html") + self.files("*.css") + self.files("*.js"):
            text = path.read_text(encoding="utf-8")
            urls = re.findall(r"""(?:src|href|url)\s*[=(]\s*["']?(https?:)?//""", text)
            self.assertFalse([u for u in urls if u], f"{path.name} loads something from the network")

    def test_every_module_import_resolves(self) -> None:
        for path in self.files("*.js"):
            for target in re.findall(r"""from\s+["'](\.[^"']+)["']""", path.read_text(encoding="utf-8")):
                self.assertTrue((path.parent / target).resolve().is_file(), f"{path.name}: {target}")

    def test_assets_referenced_by_the_page_and_css_exist(self) -> None:
        html = (WEB / "index.html").read_text(encoding="utf-8")
        for ref in re.findall(r"""(?:src|href)="([^"#:]+)\"""", html):
            self.assertTrue((WEB / ref).is_file(), ref)
        for ref in re.findall(r"""url\("(\.\./[^"]+)"\)""", TOKENS):
            self.assertTrue((WEB / "css" / ref).resolve().is_file(), ref)

    def test_badges_use_the_exact_honesty_strings(self) -> None:
        source = (WEB / "js" / "honesty.js").read_text(encoding="utf-8")
        self.assertIn('"Recorded run generated by the live pipeline"', source)
        self.assertIn('"Offline demo (fake model client)"', source)

    def test_no_real_league_names_in_the_ui(self) -> None:
        for path in self.files("*.html") + self.files("*.js") + self.files("*.css"):
            text = path.read_text(encoding="utf-8").lower()
            self.assertNotIn("premier league", text, path.name)

    def test_static_web_apps_config_serves_jsonl(self) -> None:
        config = json.loads((WEB / "staticwebapp.config.json").read_text(encoding="utf-8"))
        self.assertEqual(config["mimeTypes"][".jsonl"], "application/x-ndjson")
        self.assertIn("script-src 'self'", config["globalHeaders"]["Content-Security-Policy"])


if __name__ == "__main__":
    unittest.main()
