"""The runs published in web/data, whatever their mode: each loads and shows the labels its own manifest calls for.

This is the only e2e test that reads web/data. It passes for offline samples and for live bundles alike; what is
published is checked by its manifest, never by assuming a mode.
"""

from __future__ import annotations

import json

import pytest
from playwright.sync_api import expect

from _site import first, lower_third, manifest

pytestmark = pytest.mark.e2e

BADGES = {"foundry": "Recorded run generated by the live pipeline", "fake": "Offline demo (fake model client)"}


def test_every_published_run_shows_the_badges_its_manifest_calls_for(open_published, published_site):
    runs = json.loads((published_site["data"] / "index.json").read_text(encoding="utf-8"))["runs"]
    assert runs
    for run in runs:
        m = manifest(published_site, run["slug"])
        goal = first(published_site, run["slug"], "goal")
        page = open_published(f"?run={run['slug']}&t={lower_third(goal)['show_at_s'] + 1}")
        expect(page.locator("#mode-badge")).to_have_text(BADGES[m["pipeline"]["llm_mode"]])
        if m["faults"]["injected"]:
            expect(page.locator("#fault-badge")).to_contain_text(f"{len(m['faults']['fired'])} fired")
        else:
            expect(page.locator("#fault-badge")).to_be_hidden()
        if m["pipeline"]["llm_mode"] != "foundry":
            expect(page.locator("body")).not_to_contain_text(BADGES["foundry"])
        expect(page.locator(f".lt[data-overlay='{goal['overlay_id']}']")).to_be_visible()
