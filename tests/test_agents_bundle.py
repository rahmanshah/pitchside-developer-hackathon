"""Run bundles: written, re-read and validated; honest labels; deterministic content; schema doc is current."""

from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

from pitchside.agents.bundle import (
    FILES, LIVE_LABEL, OFFLINE_LABEL, bundle_json_schema, label_for, load_bundle, write_bundle,
)
from pitchside.agents.faults import demo_plan

from test_agents_pipeline import run

ROOT = Path(__file__).resolve().parents[1]


class BundleTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.tmp = tempfile.TemporaryDirectory()
        cls.result = run()
        cls.path = write_bundle(cls.result, Path(cls.tmp.name))
        cls.bundle = load_bundle(cls.path)

    @classmethod
    def tearDownClass(cls) -> None:
        cls.tmp.cleanup()

    def test_every_file_is_written_and_validates(self) -> None:
        for name in ("manifest", "events", "stats", "findings", "narratives", "audit", "usage", "answer_key"):
            self.assertTrue((self.path / FILES[name]).exists(), name)
        b = self.bundle
        self.assertEqual(len(b.narratives), len(self.result.records))
        self.assertEqual(len(b.findings), len(self.result.findings))
        self.assertEqual(sum(len(r.audit) for r in self.result.records), len(b.audit))
        self.assertGreater(len(b.stats), 150)  # every 30 s of a 90+ minute match

    def test_manifest_says_what_ran(self) -> None:
        m = self.bundle.manifest
        self.assertEqual(m.label, OFFLINE_LABEL)
        self.assertEqual((m.languages, m.pipeline.llm_mode), (["en", "es"], "fake"))
        self.assertEqual(len(m.personas), 4)
        self.assertEqual(set(m.pipeline.prompt_versions), {"interpreter", "explainer", "verifier", "personalizer"})
        self.assertFalse(m.faults.injected)
        self.assertEqual((m.counts.recaps, m.counts.model_fallbacks, m.budget.budget_fallbacks), (2, 0, 0))
        self.assertEqual(m.budget.model_calls, len(self.bundle.usage))
        self.assertEqual(m.generator["storyline"], "comeback")

    def test_every_narrative_has_overlay_timing_and_every_persona_in_every_language(self) -> None:
        for entry in self.bundle.narratives:
            self.assertGreater(entry.display.hide_at_s, entry.display.show_at_s)
            self.assertEqual(entry.display.show_at_s, entry.clock_s)
            self.assertEqual(len(entry.narrative.texts), len(self.bundle.manifest.personas) * 2)

    def test_shown_claims_trace_back_to_ledger_numbers(self) -> None:
        for entry in self.bundle.narratives:
            for claim in entry.narrative.claims:
                for ref in claim.refs:
                    self.assertTrue(entry.ledger.has(ref), f"{entry.job_id}: {ref}")

    def test_usage_rows_link_to_jobs_steps_and_attempts(self) -> None:
        jobs = {n.job_id for n in self.bundle.narratives if n.route == "model"}
        self.assertEqual({u.finding_id for u in self.bundle.usage}, jobs)
        self.assertTrue(all(u.step and u.step_attempt for u in self.bundle.usage))

    def test_narratives_and_audit_are_deterministic(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            again = write_bundle(run(), Path(tmp))
            for name in ("narratives", "audit", "findings", "stats", "events"):
                self.assertEqual((again / FILES[name]).read_bytes(), (self.path / FILES[name]).read_bytes(), name)


class LabelTests(unittest.TestCase):
    def test_labels_are_honest(self) -> None:
        self.assertEqual(label_for("foundry", False), "Recorded run generated by the live pipeline")
        self.assertIn("faults were deliberately injected", label_for("foundry", True))
        self.assertTrue(label_for("fake", False).startswith("Offline run (fake model client)"))

    def test_a_faulted_run_lists_every_fault_and_says_so_in_the_label(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            result = run(seed=7, storyline="end_to_end", faults=demo_plan())
            m = load_bundle(write_bundle(result, Path(tmp))).manifest
        self.assertTrue(m.faults.injected)
        self.assertIn("faults were deliberately injected", m.label)
        self.assertEqual(len(m.faults.fired), len(result.faults_fired))
        self.assertEqual(m.faults.rules, demo_plan().describe())


class SchemaDocTests(unittest.TestCase):
    def test_bundle_schema_doc_is_current(self) -> None:
        on_disk = json.loads((ROOT / "docs" / "run_bundle.schema.json").read_text(encoding="utf-8"))
        self.assertEqual(on_disk, json.loads(json.dumps(bundle_json_schema())),
                         "run `uv run pitchside schema --bundle > docs/run_bundle.schema.json`")


if __name__ == "__main__":
    unittest.main()
