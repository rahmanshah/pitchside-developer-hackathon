// Honesty labels, read from the bundle manifest. Never present recorded or offline output as live.
// Pure (tests/test_web_js.py). The badge strings are fixed; the manifest's own label is shown verbatim elsewhere.

export const LIVE_BADGE = "Recorded run generated by the live pipeline";
export const OFFLINE_BADGE = "Offline demo (fake model client)";
export const UNKNOWN_BADGE = "Unverified run: model mode unknown";
// What produced a text: never "Model" for the fake client. For a live run, the deployment named in the manifest.
export const STANDIN_SOURCE = "Offline stand-in";
export const UNVERIFIED_SOURCE = "Unverified source";
export const ROLES = ["interpreter", "explainer", "verifier", "personalizer"];

// Audit-trail text as recorded by the pipeline ("publish · director · model", "8 of 8 text(s) from the model",
// "shown: model narrative ..."), made honest for display: for the fake client every "model" becomes "offline
// stand-in", for an unknown mode "unverified source"; a Foundry run is shown as recorded.
export function auditText(text, h) {
  if (text == null || h?.mode === "foundry") return text;
  const replacement = h?.mode === "fake" ? "offline stand-in" : "unverified source";
  return String(text).replace(/(?<!fake )\b([Mm])odel\b/g,
    (_, m) => (m === "M" ? replacement[0].toUpperCase() + replacement.slice(1) : replacement));
}

// manifest: manifest.json; source: overlay.json's `source` (must agree with the manifest, or the run is unverified).
export function honesty(manifest, source) {
  const mode = manifest?.pipeline?.llm_mode;
  const agrees = !source || (source.llm_mode === mode && source.label === manifest?.label);
  const known = (mode === "foundry" || mode === "fake") && agrees;
  const faults = manifest?.faults ?? {};
  const deployments = manifest?.pipeline?.deployments ?? {};
  const sourceLabels = Object.fromEntries(ROLES.map((role) => [role,
    !known ? UNVERIFIED_SOURCE : mode === "fake" ? STANDIN_SOURCE : (deployments[role] || "unnamed deployment")]));
  return {
    sourceLabels,
    mode: known ? mode : "unknown",
    badge: !known ? UNKNOWN_BADGE : mode === "foundry" ? LIVE_BADGE : OFFLINE_BADGE,
    label: manifest?.label ?? "",
    faultsInjected: Boolean(faults.injected),
    faultsFired: Array.isArray(faults.fired) ? faults.fired.length : 0,
    faultPlan: faults.plan ?? null,
    faultRules: Array.isArray(faults.rules) ? faults.rules : [],
    costIsEstimate: !known || mode === "fake",
  };
}
